export type ChartPoint = { t: number; bps: number };

export function chartPoints(symbol: string): ChartPoint[] {
  const series = inputs.series[symbol];
  if (!series) return [];
  const transitionTimes = new Set(
    backtest.assets[symbol as keyof typeof backtest.assets]?.transitions.map(
      (transition) => Date.parse(transition.t) / 1000,
    ) ?? [],
  );

  return series.ticks.flatMap((tick, index) => {
    if (index % 15 !== 0 && !transitionTimes.has(tick.t)) return [];

    const marketUsd = Number(tick.market_usd);
    const intrinsicUsd =
      tick.intrinsic_usd != null
        ? Number(tick.intrinsic_usd)
        : series.intrinsic === "fixed_1_usd"
          ? 1
          : null;
    const marketSol = tick.market_sol == null ? null : Number(tick.market_sol);
    const intrinsicSol =
      tick.intrinsic_sol == null ? null : Number(tick.intrinsic_sol);

    let bps: number | null = null;
    if (
      marketSol != null &&
      intrinsicSol != null &&
      Number.isFinite(marketSol) &&
      intrinsicSol !== 0
    ) {
      bps = impliedGapBps(marketSol, intrinsicSol);
    } else if (
      intrinsicUsd != null &&
      Number.isFinite(marketUsd) &&
      intrinsicUsd !== 0
    ) {
      bps = impliedGapBps(marketUsd, intrinsicUsd);
    }

    return bps == null ? [] : [{ t: tick.t * 1000, bps }];
  });
}

