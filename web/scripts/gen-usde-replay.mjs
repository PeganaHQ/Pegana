// Generates web/lib/landing/usde-replay-data.ts from the committed backtest in
// docs/backtests/2025-10-10-usde-depeg/. Values are copied verbatim: the
// series keeps every existing 1-minute Pyth close inside the window (no
// interpolation, no resampling) and each receipt is the repo file's own
// content. Run from web/:  node scripts/gen-usde-replay.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "../../docs/backtests/2025-10-10-usde-depeg");
const FROM = Date.parse("2025-10-10T21:15:00Z") / 1000;
const TO = Date.parse("2025-10-10T21:55:00Z") / 1000;

const inputs = JSON.parse(readFileSync(join(dir, "inputs.json"), "utf8"));
const ticks = inputs.series.USDe.ticks
  .filter((k) => k.t >= FROM && k.t <= TO)
  .map((k) => ({ t: k.t, p: k.market_usd }));

const receipts = [];
let toml = null;
for (let i = 1; i <= 8; i++) {
  const file = `USDe-00${i}.json`;
  const b = JSON.parse(readFileSync(join(dir, "receipts", file), "utf8"));
  const at = Date.parse(b.inputs_frozen.now) / 1000;
  if (at < FROM || at > TO) continue;
  if (toml === null) toml = b.assets_toml_canonical;
  if (toml !== b.assets_toml_canonical) throw new Error(`toml differs: ${file}`);
  const { assets_toml_canonical: _omit, ...rest } = b;
  receipts.push({ file, at, ...rest });
}

const out = `// GENERATED by web/scripts/gen-usde-replay.mjs from
// docs/backtests/2025-10-10-usde-depeg/ (inputs.json + receipts/*.json).
// Do not edit by hand. Values are verbatim; the series is every existing
// 1-minute Pyth close in the window, never interpolated.

export const USDE_WINDOW = { from: ${FROM}, to: ${TO} } as const;

export const USDE_ASSETS_TOML = ${JSON.stringify(toml)};

export const USDE_TICKS: ReadonlyArray<{ t: number; p: string }> = ${JSON.stringify(ticks, null, 1)};

export const USDE_RECEIPTS = ${JSON.stringify(receipts, null, 1)} as const;
`;
writeFileSync(join(here, "../lib/landing/usde-replay-data.ts"), out);
console.log(`ticks=${ticks.length} receipts=${receipts.length}`);
