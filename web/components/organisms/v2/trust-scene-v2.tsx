// DESIGN.md 5.5 - "A real depeg, replayed". The recorded USDe event of
// 2025-10-10 (docs/backtests/2025-10-10-usde-depeg/), told as three beats the
// viewer sees: FREEZE (the real series draws in), RECOMPUTE (a cursor sweeps
// it; each receipt blooms as it is reached), MATCH (the receipt's real sha256
// is recomputed in the browser). That browser check is a HASH check of the
// published bundle, so the copy says exactly that; full verdict re-derivation
// is the pegana-replay CLI's job. A one-line caption names what is shown (the
// asset, the day, and that it is a backtest under a stated methodology), so
// nobody reads the chart as a live catch. Nothing is interpolated or invented: the data module is
// generated by web/scripts/gen-usde-replay.mjs, and "match" appears only
// after verifyReceipt has actually resolved.

/** "USDe · 2025-10-10 · backtest under methodology 0.7.0", derived from the
 *  real receipts so it cannot drift from the data it captions. */
export function replayCaption(): string {
  const day = criticalMarker().iso.slice(0, 10);
  const version = criticalMarker().bundle.methodology_version;
  return `USDe \u00b7 ${day} \u00b7 backtest under methodology ${version}`;
}

export const FREEZE_MS = 600;
export const SWEEP_MS = 2400;
export const MATCH_MS = 700;
const JUMP_MS = 180;
const EASE = [0.22, 1, 0.36, 1] as const;

/** The selected marker's label sits above it unless that would reach into the
 *  readout row, in which case it sits below. */
function labelBelow(y: number, padT: number): boolean {
  return y - 36 < padT - 4;
}

type Phase = "idle" | "freeze" | "recompute" | "match" | "done";
const ORDER: Phase[] = ["idle", "freeze", "recompute", "match", "done"];
const BEATS: Array<{ id: Phase; label: string }> = [
  { id: "freeze", label: "FREEZE" },
  { id: "recompute", label: "RECOMPUTE" },
  { id: "match", label: "MATCH" },
];

const STATE_VAR: Record<ReplayState, string> = {
  PEGGED: "var(--v2-peg)",
  DRIFT: "var(--v2-drift)",
  DEPEG: "var(--v2-depeg)",
  CRITICAL: "var(--v2-crit)",
};

function utc(iso: string): string {
  return iso.slice(11, 16);
}

function useChartWidth() {
  const ref = useRef<HTMLDivElement | null>(null);
  const [width, setWidth] = useState(CHART.w);
  useEffect(() => {
    const el = ref.current;
    if (!el || typeof ResizeObserver === "undefined") return;
    const ro = new ResizeObserver(() => {
      const w = Math.floor(el.getBoundingClientRect().width);
      if (w > 0) setWidth(w);
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  return { ref, width };
}

type Verify =
  | { status: "running" }
  | { status: "match" }
  | { status: "mismatch" }
  | { status: "error" };

/** Really recomputes the receipt hash; "match" only after it resolves. */
function useVerify(marker: ReplayMarker | null): Verify {
  const [result, setResult] = useState<{ file: string; v: Verify } | null>(
    null,
  );
  useEffect(() => {
    if (!marker) return;
    let live = true;
    verifyReceipt(marker.bundle)
      .then((r) => {
        if (live)
          setResult({
            file: marker.file,
            v: { status: r.ok ? "match" : "mismatch" },
          });
      })
      .catch(() => {
        if (live) setResult({ file: marker.file, v: { status: "error" } });
      });
    return () => {
      live = false;
    };
  }, [marker]);
  if (!marker) return { status: "running" };
  return result && result.file === marker.file
    ? result.v
    : { status: "running" };
}

/** Digits that roll in when the value changes; tabular so width is stable. */
function Rolling({ text, animate }: { text: string; animate: boolean }) {
  return (
    <span className="inline-flex tabular-nums">
      {text.split("").map((ch, i) => (
        <motion.span
          key={`${i}-${ch}`}
          initial={animate ? { y: 5, opacity: 0 } : false}
          animate={{ y: 0, opacity: 1 }}
          transition={{ duration: 0.12, ease: EASE }}
          className="inline-block"
        >
          {ch === " " ? " " : ch}
        </motion.span>
      ))}
    </span>
  );
}

/** The real sha256, characters resolving dim to bright left to right. */
function HashText({ hash, animate }: { hash: string; animate: boolean }) {
  const short = `${hash.slice(0, 8)}…${hash.slice(-6)}`;
  return (
    <span
      data-testid="result-hash"
      className="inline-flex font-mono text-[13px] tabular-nums"
      title={hash}
    >
      {short.split("").map((ch, i) => (
        <motion.span
          key={`${hash}-${i}`}
          initial={animate ? { opacity: 0.2 } : false}
          animate={{ opacity: 1 }}
          transition={{
            duration: 0.18,
            ease: EASE,
            delay: animate ? (i * 0.4) / short.length : 0,
          }}
        >
          {ch}
        </motion.span>
      ))}
    </span>
  );
}

function Marker({
  m,
  g,
  lit,
  selected,
  tabbable,
  labelled,
  animate,
  onSelect,
  onKey,
  btnRef,
}: {
  m: ReplayMarker;
  g: ChartGeometry;
  lit: boolean;
  selected: boolean;
  tabbable: boolean;
  labelled: boolean;
  animate: boolean;
  onSelect: () => void;
  onKey: (e: React.KeyboardEvent) => void;
  btnRef: (el: HTMLButtonElement | null) => void;
}) {
  const tick = tickAtOrBefore(m.at);
  const y = yFor(Number(tick.p), g);
  // Shape + a label carry the state, never colour alone.
  const shape =
    m.state === "CRITICAL"
      ? "rounded-[2px]"
      : m.state === "DEPEG"
        ? "rotate-45 rounded-[2px]"
        : "rounded-full";
  return (
    <button
      ref={btnRef}
      type="button"
      data-testid="marker"
      data-lit={lit}
      aria-pressed={selected}
      aria-label={`${m.state} at ${m.iso.slice(11, 19)} UTC, receipt ${m.file}`}
      tabIndex={tabbable ? 0 : -1}
      onClick={onSelect}
      onKeyDown={onKey}
      style={{
        left: xFor(m.at, g),
        top: y,
        visibility: lit ? "visible" : "hidden",
      }}
      className="group absolute grid size-8 -translate-x-1/2 -translate-y-1/2 place-items-center rounded-full outline-none focus-visible:ring-2 focus-visible:ring-[var(--v2-text)]"
    >
      <motion.span
        aria-hidden
        initial={animate ? { opacity: 0, scale: 0.85 } : false}
        animate={
          lit
            ? { opacity: 1, scale: selected ? 1.25 : 1 }
            : { opacity: 0, scale: 0.85 }
        }
        transition={{ duration: animate ? 0.18 : 0, ease: EASE }}
        className={`block size-3 border-2 border-[var(--v2-panel)] ${shape}`}
        style={{ background: STATE_VAR[m.state] }}
      />
      {labelled && (
        <span
          aria-hidden
          className={`pointer-events-none absolute left-1/2 -translate-x-1/2 whitespace-nowrap font-mono text-[12px] ${labelBelow(y, g.padT) ? "top-full" : "-top-5"}`}
          style={{ color: STATE_VAR[m.state] }}
        >
          {m.state}
        </span>
      )}
    </button>
  );
}

export function TrustSceneV2() {
  const head = useRevealV2<HTMLDivElement>({ index: 0 });
  const reduced = useAppReducedMotion();
  const { ref: chartRef, width } = useChartWidth();
  const markerEls = useRef<Array<HTMLButtonElement | null>>([]);
  const timers = useRef<Array<ReturnType<typeof setTimeout>>>([]);
  const raf = useRef<number | null>(null);
  const started = useRef(false);
  // Autoplay bookkeeping: how many autoplays ran, and whether the user has
  // taken over (any Replay click or marker selection).
  const autoplays = useRef(0);
  const interacted = useRef(false);
  const phaseRef = useRef<Phase>("idle");

  const total = REPLAY_MARKERS.length;
  const critical = criticalMarker();

  const [phase, setPhase] = useState<Phase>(reduced ? "done" : "idle");
  const [cursor, setCursor] = useState<number>(REPLAY_WINDOW.to);
  const [jumping, setJumping] = useState(false);
  const [litCount, setLitCount] = useState(reduced ? total : 0);
  const [selectedFile, setSelectedFile] = useState<string | null>(
    reduced ? critical.file : null,
  );

  const clearAll = useCallback(() => {
    timers.current.forEach(clearTimeout);
    timers.current = [];
    if (raf.current != null) cancelAnimationFrame(raf.current);
    raf.current = null;
  }, []);
  useEffect(() => clearAll, [clearAll]);

  const showFinal = useCallback(() => {
    clearAll();
    setPhase("done");
    setJumping(false);
    setLitCount(total);
    setCursor(critical.at);
    setSelectedFile(critical.file);
  }, [clearAll, critical.at, critical.file, total]);

  const play = useCallback(() => {
    if (reduced) {
      showFinal();
      return;
    }
    clearAll();
    setJumping(false);
    setLitCount(0);
    setSelectedFile(null);
    setCursor(REPLAY_WINDOW.from);
    setPhase("freeze");
    const later = (fn: () => void, ms: number) => {
      timers.current.push(setTimeout(fn, ms));
    };
    later(() => {
      setPhase("recompute");
      const t0 = performance.now();
      const step = (now: number) => {
        const p = Math.min(1, (now - t0) / SWEEP_MS);
        const at =
          REPLAY_WINDOW.from + p * (REPLAY_WINDOW.to - REPLAY_WINDOW.from);
        setCursor(at);
        const lit = REPLAY_MARKERS.filter((m) => m.at <= at);
        setLitCount(lit.length);
        setSelectedFile(lit.length ? lit[lit.length - 1].file : null);
        if (p < 1) {
          raf.current = requestAnimationFrame(step);
          return;
        }
        raf.current = null;
        setPhase("match");
        setJumping(true);
        setCursor(critical.at);
        setSelectedFile(critical.file);
        later(() => {
          setJumping(false);
          setPhase("done");
        }, MATCH_MS);
      };
      raf.current = requestAnimationFrame(step);
    }, FREEZE_MS);
  }, [clearAll, critical.at, critical.file, reduced, showFinal]);

  // Reduced motion: always the final state, instantly.
  useEffect(() => {
    if (reduced) showFinal();
  }, [reduced, showFinal]);

  phaseRef.current = phase;

  // Autoplays when the CHART (not the whole section, which is far taller than
  // many viewports) is mostly in view and the tab is visible, then hands
  // control to the user. If the user has not touched anything it may replay
  // once more after the chart leaves and re-enters view. Not scroll-linked.
  useEffect(() => {
    if (reduced) return;
    const el = chartRef.current;
    let inView = false;
    const visible = () => document.visibilityState !== "hidden";
    const maybe = () => {
      if (!inView || !visible()) return;
      if (interacted.current || autoplays.current >= 2) return;
      if (autoplays.current > 0 && phaseRef.current !== "done") return;
      autoplays.current += 1;
      started.current = true;
      play();
    };
    const onVisibility = () => maybe();
    document.addEventListener("visibilitychange", onVisibility);
    if (!el || typeof IntersectionObserver === "undefined") {
      inView = true;
      maybe();
      return () => document.removeEventListener("visibilitychange", onVisibility);
    }
    const io = new IntersectionObserver(
      (entries) => {
        const e = entries[entries.length - 1];
        if (!e) return;
        // "Mostly visible": 60% of the chart, or 60% of the viewport when the
        // viewport is shorter than the chart can ever fill.
        const enough =
          e.isIntersecting &&
          (e.intersectionRatio >= 0.6 ||
            (e.rootBounds != null &&
              e.intersectionRect.height >= 0.6 * e.rootBounds.height));
        if (enough && !inView) {
          inView = true;
          maybe();
        } else if (!e.isIntersecting && inView) {
          inView = false;
        }
      },
      // The fixed nav covers the top of the viewport.
      { threshold: [0, 0.3, 0.6, 1], rootMargin: "-72px 0px 0px 0px" },
    );
    io.observe(el);
    return () => {
      io.disconnect();
      document.removeEventListener("visibilitychange", onVisibility);
    };
  }, [reduced, play, chartRef]);

  const selected = REPLAY_MARKERS.find((m) => m.file === selectedFile) ?? null;
  const verify = useVerify(selected);
  const animate = !reduced;

  function select(i: number) {
    interacted.current = true;
    const m = REPLAY_MARKERS[i];
    if (phase === "freeze" || phase === "recompute") return;
    setSelectedFile(m.file);
    setJumping(true);
    setCursor(m.at);
    timers.current.push(setTimeout(() => setJumping(false), JUMP_MS));
  }

  function onKey(e: React.KeyboardEvent, i: number) {
    let next = i;
    if (e.key === "ArrowRight") next = Math.min(total - 1, i + 1);
    else if (e.key === "ArrowLeft") next = Math.max(0, i - 1);
    else if (e.key === "Home") next = 0;
    else if (e.key === "End") next = total - 1;
    else return;
    e.preventDefault();
    markerEls.current[next]?.focus();
    select(next);
  }

  const g: ChartGeometry = {
    ...CHART,
    w: width,
    h: width < 520 ? 320 : 380,
    padL: 44,
    padT: 60,
    ...fitDomain(0.1),
  };
  const ticks = linearTicks(g.yMin, g.yMax, 0.02);
  const xTicks = width < 520 ? [0, 1200, 2400] : [0, 600, 1200, 1800, 2400];
  const pts = REPLAY_TICKS.map((k) => ({
    t: k.t,
    x: xFor(k.t, g),
    y: yFor(Number(k.p), g),
  }));
  const poly = (a: typeof pts) => a.map((p) => `${p.x},${p.y}`).join(" ");
  const sweeping = phase === "recompute";
  const past = pts.filter((p) => p.t <= cursor);

  const cursorTick = tickAtOrBefore(cursor);
  const rawBps = (1 - Number(cursorTick.p)) * 10_000;
  const cursorX = xFor(cursor, g);
  const showCursor =
    phase === "recompute" ||
    phase === "match" ||
    (phase === "done" && selected != null);
  const lastLit = litCount > 0 ? REPLAY_MARKERS[litCount - 1] : null;
  const pillState: ReplayState = selected?.state ?? lastLit?.state ?? "PEGGED";
  // Readout: own row under the pill, pinned beside the cursor, flipping to the
  // cursor's left near the right edge so it never leaves the plot.
  const READOUT_W = 112;
  const readoutFlip = cursorX + 10 + READOUT_W > g.w - g.padR;
  const readoutLeft = readoutFlip
    ? Math.max(g.padL + READOUT_W, cursorX - 10)
    : Math.max(g.padL, cursorX + 10);
  const selY = selected
    ? yFor(Number(tickAtOrBefore(selected.at).p), g)
    : g.padT;
  // While sweeping the line spans the plot; once settled it starts below the
  // selected marker (and its label) so it never strikes through them.
  const lineTop =
    phase === "recompute"
      ? g.padT
      : Math.min(g.h - g.padB - 8, selY + (labelBelow(selY, g.padT) ? 40 : 12));
  const idx = (p: Phase) => ORDER.indexOf(p);
  const tabbableIdx = selected
    ? REPLAY_MARKERS.findIndex((m) => m.file === selected.file)
    : litCount > 0
      ? 0
      : -1;
  const drawn = phase !== "idle";
  // Silent while the replay steps through receipts; announced at MATCH/done.
  const announce = idx(phase) >= idx("match");

  return (
    <div className="py-20 scene:py-24">
      <div className="mx-auto w-full max-w-[1180px] px-6 sm:px-10">
        <div ref={head.ref} style={head.style} className="mb-10 max-w-[56ch]">
          <h2 className="text-balance text-[clamp(30px,4.2vw,50px)] font-medium leading-[1.05] tracking-[-0.022em]">
            Don&rsquo;t trust the score. Replay it.
          </h2>
          <p
            data-testid="replay-caption"
            className="mt-3 font-mono text-[12.5px] tracking-[0.02em] text-[var(--v2-muted)]"
          >
            {replayCaption()}
          </p>
        </div>

        <div className="min-w-0 overflow-hidden rounded-[20px] border border-[var(--v2-line)] bg-[var(--v2-panel)]">
          <div className="flex items-center justify-between gap-4 px-5 py-4 sm:px-7">
            <ol
              aria-label="Replay steps"
              className="flex min-w-0 items-center gap-3 font-mono text-[12px] tracking-[0.08em] sm:gap-5"
            >
              {BEATS.map((b) => {
                const state =
                  idx(phase) < idx(b.id)
                    ? "hidden"
                    : phase === b.id || b.id === "match"
                      ? "active"
                      : "done";
                return (
                  <li
                    key={b.id}
                    data-beat={b.id}
                    data-beat-state={state}
                    style={{
                      opacity:
                        state === "hidden" ? 0 : state === "active" ? 1 : 0.5,
                      transition: reduced
                        ? "none"
                        : "opacity 180ms cubic-bezier(.22,1,.36,1)",
                    }}
                    className="text-[var(--v2-text)]"
                  >
                    {b.label}
                  </li>
                );
              })}
            </ol>
            <button
              type="button"
              onClick={() => {
                interacted.current = true;
                started.current = true;
                play();
              }}
              className="shrink-0 rounded-[8px] border border-[var(--v2-line2)] bg-white/[0.06] px-3.5 py-1.5 font-mono text-[12.5px] text-[var(--v2-text)] transition-colors duration-200 hover:bg-white/[0.1] focus-visible:outline-2 focus-visible:outline-[var(--v2-text)]"
            >
              Replay
            </button>
          </div>

          <div className="px-2 pb-3 sm:px-5">
            <div
              ref={chartRef}
              data-testid="replay-chart"
              className="relative min-w-0"
            >
              <svg
                width={g.w}
                height={g.h}
                viewBox={`0 0 ${g.w} ${g.h}`}
                role="img"
                aria-label="USDe price in dollars, one-minute closes from 21:15 to 21:55 UTC on 2025-10-10, with the state-change receipts marked"
                className="block max-w-full"
              >
                {ticks.map((v) => (
                  <g key={v}>
                    <line
                      x1={g.padL}
                      x2={g.w - g.padR}
                      y1={yFor(v, g)}
                      y2={yFor(v, g)}
                      stroke="currentColor"
                      strokeOpacity={0.08}
                      className="text-[var(--v2-text)]"
                    />
                    <text
                      x={g.padL - 8}
                      y={yFor(v, g) + 4}
                      textAnchor="end"
                      className="fill-[var(--v2-dim)] font-mono text-[12px]"
                    >
                      {v.toFixed(2)}
                    </text>
                  </g>
                ))}
                {xTicks.map((secs) => {
                  const t = REPLAY_WINDOW.from + secs;
                  return (
                    <text
                      key={secs}
                      x={xFor(t, g)}
                      y={g.h - 8}
                      textAnchor={
                        secs === 0 ? "start" : secs === 2400 ? "end" : "middle"
                      }
                      className="fill-[var(--v2-dim)] font-mono text-[12px]"
                    >
                      {new Date(t * 1000).toISOString().slice(11, 16)}
                    </text>
                  );
                })}
                {drawn && (
                  <>
                    {/* FREEZE: faint snapshot outline as the line settles. */}
                    {animate && (
                      <motion.polyline
                        key={`snap-${phase === "freeze"}`}
                        points={poly(pts)}
                        fill="none"
                        stroke="currentColor"
                        strokeWidth={8}
                        strokeLinejoin="round"
                        className="text-[var(--v2-text)]"
                        initial={{ opacity: 0 }}
                        animate={{
                          opacity: phase === "freeze" ? [0, 0, 0.12, 0] : 0,
                        }}
                        transition={{ duration: FREEZE_MS / 1000, ease: EASE }}
                      />
                    )}
                    <motion.polyline
                      points={poly(pts)}
                      fill="none"
                      stroke="currentColor"
                      strokeWidth={1.75}
                      strokeLinejoin="round"
                      className="text-[var(--v2-text)]"
                      initial={animate ? { pathLength: 0, opacity: 1 } : false}
                      animate={{ pathLength: 1, opacity: sweeping ? 0.3 : 1 }}
                      transition={{
                        pathLength: {
                          duration: animate ? FREEZE_MS / 1000 : 0,
                          ease: EASE,
                        },
                        opacity: { duration: animate ? 0.18 : 0, ease: EASE },
                      }}
                    />
                    {sweeping && past.length > 1 && (
                      <polyline
                        points={poly(past)}
                        fill="none"
                        stroke="currentColor"
                        strokeWidth={1.75}
                        strokeLinejoin="round"
                        className="text-[var(--v2-text)]"
                      />
                    )}
                  </>
                )}
              </svg>

              {/* Cursor + live readout: transform only. */}
              {showCursor && (
                <div
                  aria-hidden
                  data-testid="cursor"
                  className="pointer-events-none absolute left-0 top-0 h-full"
                  style={{
                    transform: `translateX(${cursorX}px)`,
                    transition: jumping
                      ? `transform ${JUMP_MS}ms cubic-bezier(.22,1,.36,1)`
                      : "none",
                  }}
                >
                  <span
                    className="absolute w-px bg-[var(--v2-text)] opacity-50"
                    style={{ top: lineTop, height: g.h - g.padB - lineTop }}
                  />
                </div>
              )}
              {showCursor && (
                <div
                  aria-hidden
                  data-testid="readout"
                  className="pointer-events-none absolute top-[32px] whitespace-nowrap font-mono text-[12px] text-[var(--v2-text)]"
                  style={{
                    left: readoutLeft,
                    transform: readoutFlip ? "translateX(-100%)" : undefined,
                  }}
                >
                  {utc(new Date(cursorTick.t * 1000).toISOString())}{" "}
                  <Rolling
                    text={holderSignedPct(rawBps)}
                    animate={animate && sweeping}
                  />
                </div>
              )}

              {/* State pill: morphs PEGGED > DRIFT > DEPEG > CRITICAL. */}
              {phase !== "idle" && phase !== "freeze" && (
                <div className="pointer-events-none absolute left-11 top-0.5 sm:left-14">
                  <motion.span
                    key={pillState}
                    data-testid="state-pill"
                    initial={animate ? { opacity: 0, y: 4 } : false}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: animate ? 0.18 : 0, ease: EASE }}
                    className="inline-block rounded-full border px-2.5 py-0.5 font-mono text-[12px]"
                    style={{
                      color: STATE_VAR[pillState],
                      borderColor: STATE_VAR[pillState],
                    }}
                  >
                    {pillState}
                  </motion.span>
                </div>
              )}

              <div role="group" aria-label="State changes">
                {REPLAY_MARKERS.map((m, i) => (
                  <Marker
                    key={m.file}
                    m={m}
                    g={g}
                    lit={i < litCount}
                    selected={m.file === selectedFile}
                    tabbable={i === tabbableIdx}
                    labelled={m.file === selectedFile && i < litCount}
                    animate={animate}
                    onSelect={() => select(i)}
                    onKey={(e) => onKey(e, i)}
                    btnRef={(el) => {
                      markerEls.current[i] = el;
                    }}
                  />
                ))}
              </div>
            </div>
          </div>

          <div
            role="status"
            aria-live="polite"
            data-testid="result"
            className="flex min-h-[124px] flex-wrap sm:min-h-[80px] lg:min-h-[64px] items-center gap-x-3 gap-y-1 border-t border-[var(--v2-line)] px-5 py-4 font-mono text-[13px] text-[var(--v2-body)] sm:px-7"
          >
            {!selected && (
              <span
                aria-hidden
                className="h-3 w-56 max-w-full rounded bg-white/[0.05]"
              />
            )}
            {selected && (
              <>
                {/* Stepping receipts stay out of the live region until MATCH. */}
                <span
                  aria-hidden={announce ? undefined : true}
                  className="contents"
                >
                  <span style={{ color: STATE_VAR[selected.state] }}>
                    {selected.state}
                  </span>
                  <span className="text-[var(--v2-dim)]">&middot;</span>
                  <span className="tabular-nums">{utc(selected.iso)} UTC</span>
                </span>
                {announce && (
                  <>
                    <span className="text-[var(--v2-dim)]">&middot;</span>
                    <HashText
                      hash={selected.sha256}
                      animate={
                        animate && (phase === "match" || phase === "done")
                      }
                    />
                    <span className="text-[var(--v2-dim)]">&middot;</span>
                    {verify.status === "running" && (
                      <span className="text-[var(--v2-muted)]">
                        hashing
                      </span>
                    )}
                    {verify.status === "match" && (
                      <motion.span
                        key={`ok-${selected.file}`}
                        data-testid="verify-match"
                        initial={animate ? { opacity: 0, scale: 0.9 } : false}
                        animate={{ opacity: 1, scale: 1 }}
                        transition={{
                          duration: animate ? 0.18 : 0,
                          ease: EASE,
                        }}
                        className="inline-flex items-center gap-1.5 text-[var(--v2-text)]"
                      >
                        <Check aria-hidden className="size-3.5" />
                        hash checked in your browser: match
                      </motion.span>
                    )}
                    {verify.status === "mismatch" && (
                      <span className="text-[var(--v2-text)]">
                        hash checked in your browser: mismatch
                      </span>
                    )}
                    {verify.status === "error" && (
                      <span className="text-[var(--v2-muted)]">
                        this browser could not compute the hash
                      </span>
                    )}
                    <a
                      href={receiptUrl(selected.file)}
                      target="_blank"
                      rel="noreferrer"
                      className="ml-auto border-b border-[var(--v2-line2)] pb-px text-[12.5px] text-[var(--v2-muted)] transition-colors hover:border-white hover:text-[var(--v2-text)]"
                    >
                      View receipt
                    </a>
                  </>
                )}
              </>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
